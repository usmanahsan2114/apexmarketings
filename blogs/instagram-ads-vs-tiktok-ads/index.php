            <div class="lead" style="font-size:19px;line-height:1.6;margin-bottom:32px;color:#bbb;">
              The honest answer to "Instagram or TikTok?" is rarely a platform — it's a question about your buyer, your creative capacity, and your funnel. Benchmark numbers you read online won't transfer to your account anyway; what transfers is the decision framework. Here it is, the way we run it for clients.
            </div>
