        <h3 style="font-size:24px;font-weight:600;margin:40px 0 18px;line-height:1.3;">The challenge</h3>
        <p style="line-height:1.7;font-size:16px;color:#ddd;">678 Rid Junk operated a successful junk-removal business in Atlanta but their legacy website was hurting bookings — slow page loads, poor mobile experience, no transparent pricing, and a complicated booking flow that confused customers. They needed a modernized digital presence that converted local search traffic into booked jobs.</p>

        <h3 style="font-size:24px;font-weight:600;margin:40px 0 18px;line-height:1.3;">Our approach</h3>
        <ul style="line-height:1.7;font-size:16px;color:#ddd;padding-left:22px;">
