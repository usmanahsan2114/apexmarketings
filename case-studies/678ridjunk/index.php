                  <li style="margin-bottom:10px;line-height:1.6;">Designed a mobile-first booking flow with progressive disclosure</li>
                  <li style="margin-bottom:10px;line-height:1.6;">Engineered a Google-Maps integrated service-area display</li>
                  <li style="margin-bottom:10px;line-height:1.6;">Built a transparent quote estimator that showed pricing upfront</li>
                  <li style="margin-bottom:10px;line-height:1.6;">Implemented Google Local Services Ads + GBP optimization for "near me" search dominance</li>
        </ul>

        <h3 style="font-size:24px;font-weight:600;margin:40px 0 18px;line-height:1.3;">Technical stack</h3>
        <ul style="line-height:1.7;font-size:16px;color:#ddd;padding-left:22px;">
                  <li style="margin-bottom:8px;line-height:1.5;">WordPress + custom theme</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Tailwind CSS (mobile-first)</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Twilio for SMS booking confirmations</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Stripe for deposit collection</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Google Maps Platform API</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Calendly for scheduling</li>
        </ul>

