        <h2 style="font-size:32px;font-weight:600;margin-bottom:32px;line-height:1.25;color:#fff;text-align:center;">The full story</h2>
        
        <div style="margin-bottom:48px;padding:28px;background:#1a1a1a;border-radius:12px;box-shadow:none;border:1px solid #333;">
          <h3 style="font-size:22px;font-weight:600;margin-bottom:12px;color:rgb(20,120,190);">Client snapshot</h3>
          <p style="margin:0 0 8px;"><strong>Company:</strong> Homesware UK</p>
          <p style="margin:0 0 8px;"><strong>Location:</strong> United Kingdom — Wholesale homeware retailer</p>
          <p style="margin:0;"><strong>Industry:</strong> E-Commerce / Wholesale Homewares</p>
        </div>

        <h3 style="font-size:24px;font-weight:600;margin:40px 0 18px;line-height:1.3;">The challenge</h3>
        <p style="line-height:1.7;font-size:16px;color:#ddd;">Homesware, a UK homeware brand serving 600+ wholesale retailers + B2C, had outgrown Shopify Plus. Their B2B wholesale flow needed 12-tier customer pricing, custom approval workflows, Net-30 terms, and integration with their on-premise warehouse management system — none of which Shopify Plus could deliver cleanly. Performance was suffering (4.2s page load) and conversion was dropping.</p>

        <h3 style="font-size:24px;font-weight:600;margin:40px 0 18px;line-height:1.3;">Our approach</h3>
        <ul style="line-height:1.7;font-size:16px;color:#ddd;padding-left:22px;">
                  <li style="margin-bottom:10px;line-height:1.6;">Audited existing Shopify Plus + apps architecture; mapped 80+ business logic edge cases</li>
                  <li style="margin-bottom:10px;line-height:1.6;">Designed a custom Next.js + Postgres + Stripe architecture</li>
                  <li style="margin-bottom:10px;line-height:1.6;">Engineered a 12-tier pricing engine with bespoke per-customer overrides</li>
                  <li style="margin-bottom:10px;line-height:1.6;">Built a B2B account approval workflow with VAT/credit verification</li>
                  <li style="margin-bottom:10px;line-height:1.6;">Integrated with their on-premise Microsoft Dynamics WMS for real-time inventory</li>
                  <li style="margin-bottom:10px;line-height:1.6;">Migrated 14,000 SKUs and 600+ customer accounts with zero data loss</li>
                  <li style="margin-bottom:10px;line-height:1.6;">Soft-launched via 5% → 50% → 100% traffic split with continuous monitoring</li>
        </ul>

        <h3 style="font-size:24px;font-weight:600;margin:40px 0 18px;line-height:1.3;">Technical stack</h3>
        <ul style="line-height:1.7;font-size:16px;color:#ddd;padding-left:22px;">
                  <li style="margin-bottom:8px;line-height:1.5;">Next.js 15 with App Router (React Server Components)</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Postgres on Neon with read replicas</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Stripe (B2C checkout + B2B Invoice mode)</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Sanity CMS for product content</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Algolia for search across 14K SKUs</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Clerk for auth + B2B authorization layer</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Vercel (edge) for hosting</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Inngest for background jobs</li>
                  <li style="margin-bottom:8px;line-height:1.5;">Sentry + Datadog observability</li>
        </ul>

        <h3 style="font-size:24px;font-weight:600;margin:40px 0 18px;line-height:1.3;">Timeline</h3>
        <p style="line-height:1.7;font-size:16px;color:#ddd;">11 weeks: 2 weeks discovery → 2 weeks schema design + sync → 3 weeks build → 1 week soft launch → 1 week 50% ramp → 1 week 100% cutover → 1 week post-launch optimization</p>

        <h3 style="font-size:24px;font-weight:600;margin:40px 0 18px;line-height:1.3;">Results</h3>
        <div style="background:rgba(20,120,190,0.06);border-left:4px solid rgb(20,120,190);padding:22px 26px;border-radius:0 8px 8px 0;margin:20px 0;">
          <p style="margin:0;color:#ddd;line-height:1.7;">Specific performance numbers from this engagement are shared only with the client's written approval. We are happy to walk through verified before/after metrics for this and comparable projects on a discovery call — <a href="../../contact/" style="text-decoration:underline;">ask us</a>.</p>
        </div>

        <h3 style="font-size:24px;font-weight:600;margin:40px 0 18px;line-height:1.3;">Lessons learned</h3>
        <p style="line-height:1.7;font-size:16px;color:#ddd;">Every project teaches something. Three takeaways from this engagement:</p>
        <ul style="line-height:1.7;font-size:16px;color:#ddd;padding-left:22px;">
          <li><strong>Discovery time pays back.</strong> The upfront audit and planning sprint surfaced 80% of risks before any code or campaigns went live.</li>
          <li><strong>Phased rollout reduces risk.</strong> Soft launching to a percentage of traffic first caught edge cases that staging environments missed.</li>
          <li><strong>Ongoing optimization matters.</strong> The biggest gains came in months 2-6 as we iterated on what the data showed.</li>
        </ul>

