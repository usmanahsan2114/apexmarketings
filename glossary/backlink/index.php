            <h2 class="cs-font_36 mb-4">What it is</h2>
              <p>A backlink (also called an inbound link) is a hyperlink on one website that points to a page on another website. If a news site links to your article, that link is a backlink for your page. Backlinks are the foundation of off-page <a href="../seo/">SEO</a> because search engines read them as signals about which pages other people find useful and trustworthy.</p>
              <p>Not every link carries the same weight. A link from a respected, topically related publication tells Google far more than a link buried in an unrelated comments section. The collective strength of a site's backlinks is often described loosely as its "link authority" or domain authority.</p>
            <h2 class="cs-font_36 mb-4">Why it matters</h2>
              <p>Search engines can't directly judge whether content is accurate or helpful, so they look for external signals. A backlink acts like a citation: when many credible sites reference your page, it suggests the page is worth surfacing. That is why backlinks remain one of the strongest off-page ranking factors, alongside content quality and <a href="../technical-seo/">technical SEO</a>.</p>
              <p>Authority also compounds. Pages with strong, relevant backlinks tend to rank for more keywords, attract more links over time, and pass some of that trust to other pages on the same site through internal linking.</p>
            <h2 class="cs-font_36 mb-4">Quality vs quantity</h2>
              <p>Chasing a high link count is a common mistake. A handful of editorial links from trusted, relevant sites usually outperforms hundreds of links from directories, link farms, or spammy blogs. When you evaluate a backlink, the factors that matter most are:</p>
              <ul>
                <li><strong>Relevance</strong> — is the linking site related to your topic or industry?</li>
                <li><strong>Trust</strong> — is it a credible, well-regarded source rather than a spam network?</li>
                <li><strong>Context</strong> — is the link inside genuine editorial content, or stuffed in a footer or sidebar?</li>
                <li><strong>Anchor text</strong> — does the clickable text describe the destination naturally, without over-optimization?</li>
              </ul>
            <h2 class="cs-font_36 mb-4">How to earn them (white-hat)</h2>
              <p>The durable way to build backlinks is to <em>earn</em> them, never to buy them. Buying or trading links at scale violates Google's spam policies and risks ranking penalties or de-indexing. White-hat tactics that earn links honestly include:</p>
              <ul>
                <li>Publishing genuinely useful, original content people want to cite.</li>
                <li>Original research, data, or tools that journalists and bloggers reference.</li>
                <li>Guest contributions and expert commentary on reputable sites.</li>
                <li>Digital PR and outreach that highlights work worth covering.</li>
              </ul>
              <p>Earned links take longer than shortcuts, but they hold up against algorithm updates and rarely put a site at risk.</p>
            <h2 class="cs-font_36 mb-4">Related terms</h2>
