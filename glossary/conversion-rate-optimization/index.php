            <h2 class="cs-font_36 mb-4">What it is</h2>
              <p>Conversion Rate Optimization is the discipline of improving the percentage of visitors who take a desired action — buy a product, submit a form, book a demo. CRO is high-leverage because every percentage point of conversion improvement multiplies every traffic source you're already running.</p>
              <p><strong>CRO methods we use:</strong></p>
              <p><strong>A/B testing:</strong> two versions of a page run simultaneously; whichever converts better wins<br><strong>Heatmaps + session replays:</strong> see where users click, scroll, and drop off (Microsoft Clarity, Hotjar)<br><strong>User testing:</strong> watch real users try to accomplish tasks on your site<br><strong>Funnel analysis:</strong> identify the single biggest drop-off step in your conversion path<br><strong>Iterative improvement:</strong> ship small wins continuously; don't wait for perfect</p>
              <h2 class="cs-font_36 mb-4">Real example</h2>
              <p>A SaaS landing page converts at 2.1%. The team runs 6 A/B tests over 90 days — testing headline, hero image, CTA copy, form length, social proof position, and pricing transparency. After all wins compound, conversion is at 4.8% — 2.3x more revenue from the same traffic.</p>
