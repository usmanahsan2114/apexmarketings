            <h2 class="cs-font_36 mb-4">What it is</h2>
              <p>Cost Per Acquisition (sometimes Cost Per Action) is the unit-economics metric that actually matters in performance marketing. CPC tells you how much each click costs; CPA tells you how much each customer or lead costs. CPA is calculated as: (Total ad spend) / (Total conversions).</p>
              <p><strong>What's a 'good' CPA?</strong> Depends on your customer LTV (Lifetime Value). General rule:</p>
              <p><strong>Healthy:</strong> CPA = 10-20% of LTV<br><strong>Aggressive:</strong> CPA = 20-30% of LTV (sustainable if cash flow allows)<br><strong>Unsustainable:</strong> CPA > 50% of LTV (you're losing money)</p>
              <p><strong>How to reduce CPA:</strong> better landing pages (highest leverage), tighter targeting, better ad creative, longer retargeting windows, post-purchase upsells to lift LTV (which makes higher CPAs sustainable).</p>
              <h2 class="cs-font_36 mb-4">Real example</h2>
              <p>A SaaS company with USD 1,500 LTV pays USD 200 CPA. That's healthy (13% of LTV). They optimize landing pages, CPA drops to USD 120. Now they can scale ad spend without losing margin.</p>
