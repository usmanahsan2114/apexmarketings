            <h2 class="cs-font_36 mb-4">What it is</h2>
              <p>A landing page differs from a homepage in scope and goal. Homepages serve everyone who lands on your site for any reason. Landing pages serve one specific audience (the people who clicked one specific ad) with one specific goal (the conversion you want them to take).</p>
              <p><strong>Why dedicated landing pages outperform homepages for paid traffic:</strong> message-match (the headline matches the ad), focused CTA (no competing options), no distractions (no navigation menu, no off-topic content), built-in social proof tied to the specific offer.</p>
              <p><strong>Typical landing page conversion rates (2026):</strong></p>
              <p>Generic homepage as landing page: 1-2%<br>Basic landing page: 3-5%<br>Optimized landing page: 5-10%<br>Best-in-class: 10-20% (rare; usually warm audiences + strong offer)</p>
              <h2 class="cs-font_36 mb-4">Real example</h2>
