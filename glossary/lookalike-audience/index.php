            <h2 class="cs-font_36 mb-4">What it is</h2>
              <p>Lookalike audiences are Meta's (and Google's, called 'similar audiences') way of expanding cold-acquisition targeting. You give the platform a 'seed audience' (your customer list, your high-value site visitors, your purchasers) and the platform finds new people who behave similarly.</p>
              <p><strong>Best seed audiences:</strong></p>
              <p><strong>Recent purchasers</strong> (last 30-90 days) — highest signal<br><strong>High-LTV customers</strong> (top 10% by lifetime spend) — even stronger signal if you have the data<br><strong>Email subscribers who opened recent emails</strong><br><strong>Site visitors who hit your pricing page</strong> (intent signal)</p>
              <p><strong>Lookalike best practices:</strong> seed audience minimum 100 people (Meta's threshold), ideally 1,000+; refresh seed audience every 30-60 days as customer base evolves; test multiple seed audiences against each other; combine with interest targeting for cold acquisition.</p>
              <h2 class="cs-font_36 mb-4">Real example</h2>
              <p>A Shopify brand creates a lookalike from their top 10% LTV customers (n=850). They run Meta Ads to a 1% lookalike of that audience. The lookalike campaign achieves 4.2x ROAS vs 2.6x ROAS for their interest-targeting campaigns.</p>
