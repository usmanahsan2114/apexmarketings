            <h2 class="cs-font_36 mb-4">What it is</h2>
              <p>The classic marketing funnel has 4-5 stages: <strong>Awareness</strong> (people first hear about you) → <strong>Consideration</strong> (people evaluate vs alternatives) → <strong>Conversion</strong> (people buy) → <strong>Retention</strong> (people buy again) → <strong>Advocacy</strong> (people refer others).</p>
              <p><strong>Which channels work at which stage:</strong></p>
              <p><strong>Awareness:</strong> SEO content, Meta Ads, podcast sponsorships, PR, influencer content<br><strong>Consideration:</strong> Comparison content, case studies, webinars, demos, email nurture<br><strong>Conversion:</strong> Google Search Ads (high intent), retargeting, landing-page optimization<br><strong>Retention:</strong> Email and SMS flows, loyalty programs, account-based outreach<br><strong>Advocacy:</strong> Referral programs, customer-success outreach, review campaigns</p>
              <p>Most businesses over-invest in conversion (paid ads) and under-invest in awareness and retention. The brands compounding fastest are running all 5 stages simultaneously.</p>
              <h2 class="cs-font_36 mb-4">Real example</h2>
              <p>An e-commerce brand maps their funnel: 10K visitors/month (awareness) → 2K product-page views (consideration) → 200 cart adds → 80 purchases → 30 repeat purchases over 12 months. They identify the biggest leak (10% cart-to-purchase rate) and focus CRO efforts there.</p>
