            <h2 class="cs-font_36 mb-4">What it is</h2>
              <p>95-98% of first-time website visitors don't convert. Retargeting recovers a portion of those by showing them ads after they leave — on Meta, Google Display, or YouTube — to bring them back.</p>
              <p><strong>Common retargeting campaigns:</strong></p>
              <p><strong>Site visitors</strong> (people who visited any page in last 30 days)<br><strong>Product viewers</strong> (people who viewed specific products)<br><strong>Cart abandoners</strong> (added to cart, didn't check out)<br><strong>Past customers</strong> (cross-sell or repeat purchase)<br><strong>Email list</strong> (people who signed up but haven't bought)</p>
              <p>Retargeting consistently produces 3-10x higher ROAS than cold acquisition campaigns. The trade-off: audience size is small (limited to people who already interacted with your brand), so retargeting alone can't scale — you need cold acquisition feeding it.</p>
              <h2 class="cs-font_36 mb-4">Real example</h2>
              <p>An e-commerce brand runs cold Meta Ads at 2.1x ROAS. They add a retargeting campaign targeting cart-abandoners over the last 7 days. Retargeting ROAS comes in at 8.4x. Blended ROAS across both campaigns improves to 3.2x.</p>
