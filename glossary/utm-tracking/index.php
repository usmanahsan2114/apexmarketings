            <h2 class="cs-font_36 mb-4">What it is</h2>
              <p>UTM (Urchin Tracking Module) parameters are query-string tags appended to URLs that pass campaign info to Google Analytics, Meta, and other measurement tools. Without UTMs, you can't tell which campaign, email, or social post drove a specific conversion.</p>
              <p><strong>The 5 standard UTM parameters:</strong></p>
              <p><strong>utm_source</strong> — the platform (google, facebook, newsletter, linkedin)<br><strong>utm_medium</strong> — the channel type (cpc, email, social, organic, referral)<br><strong>utm_campaign</strong> — the specific campaign name (spring_sale_2026, q2_launch)<br><strong>utm_term</strong> — the keyword (paid search only)<br><strong>utm_content</strong> — the ad variant or link position (cta_button_top, image_ad_v2)</p>
              <p><strong>UTM best practices:</strong> lowercase everything (utm values are case-sensitive), use underscores not spaces, maintain a UTM naming convention document, never UTM internal links on your own site (breaks attribution), use a UTM builder (Google's free Campaign URL Builder is the standard).</p>
              <h2 class="cs-font_36 mb-4">Real example</h2>
              <p>A marketing team runs the same offer across 4 channels. Without UTMs, Google Analytics shows '300 conversions from /pricing' with no source attribution. With UTMs, they see: 120 from Meta cold ads, 80 from Meta retargeting, 60 from email newsletter, 40 from LinkedIn. They double down on Meta retargeting (highest CPA-efficiency).</p>
